import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

// Pin upgrades deliberately; validation itself never fetches the vocabulary.
const VERSION = '30.1';
const SOURCE = `https://schema.org/version/${VERSION}/schemaorg-current-https.jsonld`;
const bytes = process.argv[2]
  ? await readFile(process.argv[2])
  : Buffer.from(await (await fetch(SOURCE).then(response => {
      if (!response.ok) throw new Error(`Vocabulary download failed: ${response.status}`);
      return response;
    })).arrayBuffer());
const document = JSON.parse(bytes.toString('utf8'));
if (!Array.isArray(document['@graph'])) throw new Error('Missing Schema.org graph');
const types = [...new Set(document['@graph'].filter(node =>
  [node['@type']].flat().some(type => type === 'rdfs:Class' || type === 'http://www.w3.org/2000/01/rdf-schema#Class')
).map(node => String(node['@id']).replace(/^(?:schema:|https?:\/\/schema\.org\/)/, '')).filter(name => /^[A-Za-z][A-Za-z0-9]*$/.test(name)))].sort();
if (types.length < 800 || !types.includes('ExerciseGym') || types.includes('name')) throw new Error('Unexpected vocabulary contents');
const hash = createHash('sha256').update(bytes).digest('hex');
await writeFile(new URL('../src/schema-vocabulary-data.ts', import.meta.url),
  `// Generated by scripts/update-schema-vocabulary.mjs; do not edit manually.\n// Source: ${SOURCE}\n// Source SHA-256: ${hash}\nexport const SCHEMA_VOCABULARY_VERSION = '${VERSION}';\nexport const SCHEMA_VOCABULARY_TYPES: readonly string[] = ${JSON.stringify(types, null, 2)};\n`);
console.log(`Generated ${types.length} Schema.org ${VERSION} class names (${hash}).`);
