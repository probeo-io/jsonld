import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

// Pin upgrades deliberately; validation itself never fetches the vocabulary.
const VERSION = '30.1';
const SOURCE = `https://schema.org/version/${VERSION}/schemaorg-current-https.jsonld`;
const bytes = process.argv[2]
  ? await readFile(process.argv[2])
  : Buffer.from(await (await fetch(SOURCE).then(response => {
      if (!response.ok) throw new Error(`Vocabulary download failed: ${response.status}`);
      return response;
    })).arrayBuffer());
const document = JSON.parse(bytes.toString('utf8'));
if (!Array.isArray(document['@graph'])) throw new Error('Missing Schema.org graph');
const types = [...new Set(document['@graph'].filter(node =>
  [node['@type']].flat().some(type => type === 'rdfs:Class' || type === 'http://www.w3.org/2000/01/rdf-schema#Class')
).map(node => String(node['@id']).replace(/^(?:schema:|https?:\/\/schema\.org\/)/, '')).filter(name => /^[A-Za-z][A-Za-z0-9]*$/.test(name)))].sort();
if (types.length < 800 || !types.includes('ExerciseGym') || types.includes('name')) throw new Error('Unexpected vocabulary contents');
const hash = createHash('sha256').update(bytes).digest('hex');
await writeFile(new URL('../src/schema-vocabulary-data.ts', import.meta.url),
  `// Generated by scripts/update-schema-vocabulary.mjs; do not edit manually.\n// Source: ${SOURCE}\n// Source SHA-256: ${hash}\nexport const SCHEMA_VOCABULARY_VERSION = '${VERSION}';\nexport const SCHEMA_VOCABULARY_TYPES: readonly string[] = ${JSON.stringify(types, null, 2)};\n`);
console.log(`Generated ${types.length} Schema.org ${VERSION} class names (${hash}).`);

const localName = value => typeof value === 'string' && /^(schema:|https?:\/\/schema\.org\/)/.test(value)
  ? value.replace(/^(schema:|https?:\/\/schema\.org\/)/, '') : null;
const refs = value => [value ?? []].flat().map(item => localName(item?.['@id'])).filter(Boolean).sort();
const classSet = new Set(types);
const parents = {}, properties = {}, enumerationValues = {};
for (const node of document['@graph']) {
  const name = localName(node['@id']);
  if (!name) continue;
  const kinds = [node['@type'] ?? []].flat();
  if (classSet.has(name)) parents[name] = refs(node['rdfs:subClassOf']);
  else if (kinds.includes('rdf:Property')) properties[name] = {
    domains: refs(node['schema:domainIncludes']), ranges: refs(node['schema:rangeIncludes']),
    parents: refs(node['rdfs:subPropertyOf']), supersededBy: refs(node['schema:supersededBy']),
  };
  else {
    const declaredTypes = kinds.map(localName).filter(type => type && classSet.has(type));
    if (declaredTypes.length) enumerationValues[name] = declaredTypes.sort();
  }
}
const sorted = value => Object.fromEntries(Object.entries(value).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0));
await writeFile(new URL('../src/schema-model-data.ts', import.meta.url),
  `// Generated by scripts/update-schema-vocabulary.mjs; do not edit manually.\n// Source: ${SOURCE}\n// Source SHA-256: ${hash}\n` +
  `export const TYPE_PARENTS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(sorted(parents))};\n` +
  `export const PROPERTY_DEFINITIONS: Readonly<Record<string, { domains: readonly string[]; ranges: readonly string[]; parents: readonly string[]; supersededBy: readonly string[] }>> = ${JSON.stringify(sorted(properties))};\n` +
  `export const ENUMERATION_VALUES: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(sorted(enumerationValues))};\n`);
console.log(`Generated inheritance, ${Object.keys(properties).length} properties and ${Object.keys(enumerationValues).length} vocabulary values.`);
